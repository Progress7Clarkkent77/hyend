Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Clean URLs on web (no #). No-op on mobile.
  usePathUrlStrategy();

  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Wait for Firebase to restore the saved session so route guards see the
  // real sign-in state on a page refresh.
  await FirebaseAuth.instance.authStateChanges().first;

  await GetStorage.init();

  // AuthController MUST be registered before ThemeController, because
  // ThemeController does Get.find<AuthController>() when it is created.
  Get.put(AuthController(), permanent: true);
  final themeCtrl = Get.put(ThemeController(), permanent: true);

  // If a session was restored (refresh / app relaunch), load the saved theme
  // now so the very first frame already uses the right mode.
  if (FirebaseAuth.instance.currentUser != null) {
    try {
      await themeCtrl.loadTheme();
    } catch (e) {
      debugPrint('Could not load saved theme: $e');
    }
  }

  // Switch the whole app live whenever setDark() / setLight() / loadTheme()
  // changes the value.
  ever<bool>(themeCtrl.isDarkMode, (isDark) {
    Get.changeThemeMode(isDark ? ThemeMode.dark : ThemeMode.light);
  });

  runApp(
    MyApp(
      initialMode: themeCtrl.isDarkMode.value
          ? ThemeMode.dark
          : ThemeMode.light,
    ),
  );
}

/// Controller registration. `fenix: true` recreates a lazy controller if it
/// was disposed and is requested again.
class AppBinding extends Bindings {
  @override
  void dependencies() {
    // AuthController and ThemeController are already registered in main().
    Get.put(StartupController(), permanent: true);

    // Navigation helper. Permanent so every page (even a web refresh straight
    // onto /cart or /orders) can Get.find() it.
    Get.put(EcommerceLiveNavController(), permanent: true);

    Get.lazyPut(() => AccountController(), fenix: true);

    Get.lazyPut(() => VerifiedController(), fenix: true);

    // Storefront
    // Permanent = one store instance for the whole session, so home and the
    // details page share the same product list and selected product.
    Get.put(EcommerceStoreController(), permanent: true);
    Get.lazyPut(() => EcommerceCartController(), fenix: true);
    Get.lazyPut(() => OrderController(), fenix: true);

    // Admin
    Get.lazyPut(() => AdminAuthController(), fenix: true);
    Get.lazyPut(() => EcommerceAdminDashboardController(), fenix: true);
    Get.lazyPut(() => ManageOrdersController(), fenix: true);
    Get.lazyPut(() => ManageProductsController(), fenix: true);
    Get.lazyPut(() => UploadProductController(), fenix: true);
    Get.lazyPut(() => BlackFridayController(), fenix: true);
  }
}

